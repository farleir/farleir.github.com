// Classe da Partícula
class Particle {
    constructor(x, y, text = null) {
        this.x = x;
        this.y = y;
        this.size = text ? 5 : Math.random() * 2 + 1; // Partículas com texto são maiores
        this.baseX = this.x;
        this.baseY = this.y;
        this.density = (Math.random() * 30) + 1;
        this.text = text;
        this.color = text ? 'rgba(14, 165, 233, 0.4)' : 'rgba(14, 165, 233, 0.1)'; // sky-500 com opacidade menor
        this.font = text ? '12px Inter' : null;
    }

    draw() {
        ctx.fillStyle = this.color;
        ctx.beginPath();
        ctx.arc(this.x, this.y, this.size, 0, Math.PI * 2);
        ctx.closePath();
        ctx.fill();

        if (this.text) {
            ctx.font = this.font;
            const isDark = document.documentElement.classList.contains('dark');
            ctx.fillStyle = isDark ? 'rgba(226, 232, 240, 0.7)' : 'rgba(15, 23, 42, 0.7)'; // slate-200 ou slate-900 (com 70% opacidade)
            // Tenta centralizar o texto na partícula
            const textWidth = ctx.measureText(this.text).width;
            ctx.fillText(this.text, this.x - textWidth / 2, this.y + 4);
        }
    }

    update() {
        let dx = mouse.x - this.x;
        let dy = mouse.y - this.y;
        let distance = Math.sqrt(dx * dx + dy * dy);

        if (distance < mouse.radius && mouse.x !== null) { // Adicionado cheque de mouse.x
            let forceDirectionX = dx / distance;
            let forceDirectionY = dy / distance;

            let maxDistance = mouse.radius;
            // Efeito de "repelir" do mouse
            let force = (maxDistance - distance) / maxDistance;
            let directionX = (forceDirectionX * force * this.density);
            let directionY = (forceDirectionY * force * this.density);
            this.x -= directionX;
            this.y -= directionY;
        } else {
            // Retorna suavemente à posição original
            if (this.x !== this.baseX) {
                let dx = this.x - this.baseX;
                this.x -= dx / 10;
            }
            if (this.y !== this.baseY) {
                let dy = this.y - this.baseY;
                this.y -= dy / 10;
            }
        }
        // Limita as partículas dentro do canvas
        if (this.x < 0) this.x = canvas.width;
        if (this.x > canvas.width) this.x = 0;
        if (this.y < 0) this.y = canvas.height;
        if (this.y > canvas.height) this.y = 0;

        this.draw();
    }
}

// Inicializa as partículas - Lógica de distribuição melhorada
function initParticles(count) {
    particles = [];
    const skillCount = skills.length;
    const particlesPerSkill = Math.max(1, Math.floor(count / skillCount));
    let particleIndex = 0;

    for (let i = 0; i < skillCount; i++) {
        for (let j = 0; j < particlesPerSkill; j++) {
            if (particleIndex >= count) break;
            let x = Math.random() * canvas.width;
            let y = Math.random() * canvas.height;
            // Adiciona texto apenas à primeira partícula de cada "grupo" de skill
            let text = (j === 0) ? skills[i] : null;
            particles.push(new Particle(x, y, text));
            particleIndex++;
        }
    }
     // Preenche com partículas sem texto se sobraram
    while(particleIndex < count){
         let x = Math.random() * canvas.width;
         let y = Math.random() * canvas.height;
         particles.push(new Particle(x, y, null));
         particleIndex++;
    }
}


// Conecta partículas próximas com linhas
function connectParticles() {
    let opacity = 0.5;
    for (let a = 0; a < particles.length; a++) {
        for (let b = a + 1; b < particles.length; b++) { // Começa de a+1 para evitar duplicatas
            let dx = particles[a].x - particles[b].x;
            let dy = particles[a].y - particles[b].y;
            let distance = Math.sqrt(dx * dx + dy * dy);

            // Aumentar a distância máxima para conectar mais pontos
            const maxConnectDistance = 150;
            if (distance < maxConnectDistance) {
                opacity = 1 - (distance / maxConnectDistance);
                const isDark = document.documentElement.classList.contains('dark');
                const lineOpacity = isDark ? opacity * 0.3 : opacity * 0.8;
                ctx.strokeStyle = `rgba(14, 165, 233, ${lineOpacity})`;
                ctx.lineWidth = 1;
                ctx.beginPath();
                ctx.moveTo(particles[a].x, particles[a].y);
                ctx.lineTo(particles[b].x, particles[b].y);
                ctx.stroke();
            }
        }
    }
}

// Loop de Animação
function animate() {
    ctx.clearRect(0, 0, canvas.width, canvas.height);
    for (let i = 0; i < particles.length; i++) {
        particles[i].update();
    }
    connectParticles();
    requestAnimationFrame(animate);
}

// Inicia tudo
resizeCanvas(); // Chama uma vez para configurar o tamanho inicial
// Pequeno atraso para garantir que a tela esteja dimensionada antes de animar
setTimeout(() => {
     animate();
}, 100);
